import { QueryClient } from '@tanstack/react-query';

export const queryClient = new QueryClient({
  defaultOptions: {
    queries: {
      /**
       * Данные считаются свежими 5 минут — в течение этого времени повторных запросов нет.
       * Для волатильных данных снижайте значение (например, staleTime: 0 для real-time лент).
       */
      staleTime: 5 * 60 * 1000,

      /**
       * Неиспользуемый/неактивный кэш хранится 10 минут до сборки мусора.
       * Позволяет сохранить данные при навигации назад на страницу.
       */
      gcTime: 10 * 60 * 1000,

      /**
       * Повторять неудачные запросы до 2 раз с экспоненциальной задержкой.
       * Установите false для мутаций или заведомо 4xx-эндпоинтов.
       */
      retry: 2,

      /**
       * Не перезапрашивать данные при фокусе вкладки — снижает шум в дашбордах.
       * Установите true для приложений, требующих актуальности в реальном времени.
       */
      refetchOnWindowFocus: false,

      /** Перезапрашивать данные при восстановлении соединения после офлайна. */
      refetchOnReconnect: true,
    },
    mutations: {
      /** Не повторять мутации — побочные эффекты не должны дублироваться. */
      retry: 0,
    },
  },
});
